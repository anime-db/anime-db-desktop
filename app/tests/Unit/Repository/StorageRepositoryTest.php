declare(strict_types=1);

namespace App\Tests\Unit\Repository;

use App\Doctrine\Type\RatingType;
use App\Doctrine\Type\UnixTimestampType;
use App\Entity\Enum\StorageType;
use App\Entity\Storage;
use App\Repository\StorageRepository;
use Doctrine\DBAL\DriverManager;
use Doctrine\DBAL\Types\Type;
use Doctrine\ORM\EntityManager;
use Doctrine\ORM\ORMSetup;
use Doctrine\ORM\Tools\SchemaTool;
use PHPUnit\Framework\TestCase;

final class StorageRepositoryTest extends TestCase
{
    private EntityManager $entityManager;
    private StorageRepository $repository;

    protected function setUp(): void
    {
        if (!Type::hasType(UnixTimestampType::NAME)) {
            Type::addType(UnixTimestampType::NAME, UnixTimestampType::class);
        }
        if (!Type::hasType(RatingType::NAME)) {
            Type::addType(RatingType::NAME, RatingType::class);
        }

        $config = ORMSetup::createAttributeMetadataConfig([\dirname(__DIR__, 3).'/src/Entity'], true);
        $config->enableNativeLazyObjects(true);

        $connection = DriverManager::getConnection(['driver' => 'pdo_sqlite', 'memory' => true], $config);
        $this->entityManager = new EntityManager($connection, $config);

        $schemaTool = new SchemaTool($this->entityManager);
        $schemaTool->createSchema($this->entityManager->getMetadataFactory()->getAllMetadata());

        $this->repository = new StorageRepository($this->entityManager);
    }

    public function testHasAnyReturnsFalseWhenNoStorageExists(): void
    {
        $this->assertFalse($this->repository->hasAny());
    }

    public function testHasAnyReturnsTrueWhenStorageExists(): void
    {
        $this->entityManager->persist(new Storage('Main folder', 'D:\\Anime', StorageType::Folder));
        $this->entityManager->flush();

        $this->assertTrue($this->repository->hasAny());
    }
}
