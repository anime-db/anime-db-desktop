'use strict';

const fs   = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const rootDir    = path.resolve(__dirname, '..');
const appDir     = path.join(rootDir, 'app');
const OUTPUT     = path.join(rootDir, 'resources', 'third-party-licenses', 'COMPOSER-PACKAGES.md');
// Where app/ lands inside the installation directory (see "files" in package.json).
const SHIPPED_VENDOR = 'resources/app/app/vendor';
const NOT_FOUND  = 'NOT FOUND';

const LICENSE_FILE = /^(licen[cs]e|copying|unlicense)([-_.].*)?$/i;

/**
 * @param {string} packageDir
 * @returns {string|null} name of the license file inside the package directory, or null
 */
function findLicenseFile(packageDir) {
    if (!fs.existsSync(packageDir)) {
        return null;
    }
    const names = fs.readdirSync(packageDir, { withFileTypes: true })
        .filter((entry) => entry.isFile() && LICENSE_FILE.test(entry.name))
        .map((entry) => entry.name)
        .sort();

    return names[0] ?? null;
}

/**
 * @param {string} vendorDir
 * @returns {{ name: string, version: string, license: string, file: string|null }[]} production
 *          packages sorted by name
 */
function collectPackages(vendorDir) {
    const output = execFileSync('composer', ['licenses', '--no-dev', '--format=json', '--no-interaction'], {
        cwd: appDir,
        encoding: 'utf8',
        maxBuffer: 16 * 1024 * 1024,
    });
    const { dependencies } = JSON.parse(output);

    return Object.keys(dependencies)
        .sort()
        .map((name) => ({
            name,
            version: dependencies[name].version,
            license: dependencies[name].license.join(', ') || 'none',
            file: findLicenseFile(path.join(vendorDir, ...name.split('/'))),
        }));
}

/**
 * @param {{ name: string, version: string, license: string, file: string|null }[]} packages
 * @returns {string}
 */
function render(packages) {
    const rows = packages.map((pkg) => [
        pkg.name,
        pkg.version,
        pkg.license,
        pkg.file === null ? NOT_FOUND : `${SHIPPED_VENDOR}/${pkg.name}/${pkg.file}`,
    ]);
    const header = ['Package', 'Version', 'License', 'License text'];
    const widths = header.map((title, i) => Math.max(title.length, ...rows.map((row) => row[i].length)));
    const line   = (cells) => `| ${cells.map((cell, i) => cell.padEnd(widths[i])).join(' | ')} |`;

    return [
        '# PHP packages bundled with AnimeDB',
        '',
        'Production dependencies of `app/composer.json` (`composer licenses --no-dev`), shipped under',
        '`resources/app/app/vendor/`. Each package carries its own license text in its directory; the path',
        'is relative to the AnimeDB installation directory. `' + NOT_FOUND + '` means the package ships no license file.',
        '',
        '<!-- Generated by scripts/generate-composer-licenses.js; regenerate with: node scripts/generate-composer-licenses.js -->',
        '',
        line(header),
        `|${widths.map((width) => '-'.repeat(width + 2)).join('|')}|`,
        ...rows.map(line),
        '',
    ].join('\n');
}

function main() {
    const packages = collectPackages(path.join(appDir, 'vendor'));
    const content  = render(packages);
    const missing  = packages.filter((pkg) => pkg.file === null).map((pkg) => pkg.name);

    for (const name of missing) {
        console.error(`No license file in the package directory: ${name}`);
    }

    if (process.argv.includes('--check')) {
        const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
        if (current !== content) {
            console.error('COMPOSER-PACKAGES.md is out of date; run: node scripts/generate-composer-licenses.js');
            process.exitCode = 1;
        }
        return;
    }

    fs.writeFileSync(OUTPUT, content);
    console.log(`Wrote ${path.relative(rootDir, OUTPUT)}: ${packages.length} packages, ${missing.length} without a license file`);
}

if (require.main === module) {
    main();
}

module.exports = { findLicenseFile, render, LICENSE_FILE, NOT_FOUND, SHIPPED_VENDOR };
